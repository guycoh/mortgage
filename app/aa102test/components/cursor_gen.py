"""Build app/aa102test/components/cursor.css — the board's own cursors as inline SVG.

One drawing per cursor, emitted at 1x and 2x so it stays sharp on high-DPI
screens (Chrome rasterises an SVG cursor at its declared size).
"""
from urllib.parse import quote

SHADOW = (
    '<filter id="s" x="-40%" y="-40%" width="180%" height="180%">'
    '<feDropShadow dx="0" dy="1" stdDeviation="0.9" flood-color="#0b0d1a" flood-opacity="0.32"/>'
    '</filter>'
)

# A slightly softened Figma-style arrow: straight tail, rounded joins.
ARROW = (
    "M5.6 3.4 L5.6 18.9 C5.6 19.5 6.3 19.8 6.7 19.4 L10.2 15.9 "
    "L12.7 21.3 C12.9 21.8 13.5 22 14 21.8 L15.5 21.1 C16 20.9 16.2 20.3 16 19.8 "
    "L13.5 14.5 L18.4 14.3 C19 14.3 19.3 13.6 18.9 13.2 L6.7 2.8 C6.3 2.4 5.6 2.7 5.6 3.4 Z"
)


def arrow(fill, size):
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 24 24">'
        f'<defs>{SHADOW}</defs>'
        f'<path d="{ARROW}" fill="{fill}" stroke="#fff" stroke-width="1.5" stroke-linejoin="round" filter="url(#s)"/>'
        '</svg>'
    )


def beam(size):
    # slim I-beam with soft serifs, white halo for any background
    d = "M9 4.5 C10.6 4.5 11.4 5 12 5.8 C12.6 5 13.4 4.5 15 4.5 M12 5.8 L12 18.2 M9 19.5 C10.6 19.5 11.4 19 12 18.2 C12.6 19 13.4 19.5 15 19.5"
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 24 24">'
        f'<defs>{SHADOW}</defs>'
        f'<g fill="none" stroke-linecap="round" filter="url(#s)">'
        f'<path d="{d}" stroke="#fff" stroke-width="3.6"/>'
        f'<path d="{d}" stroke="#1d1f2c" stroke-width="1.5"/>'
        '</g></svg>'
    )


def uri(svg):
    return 'url("data:image/svg+xml,' + quote(svg, safe=" =:/;,'()") + '")'


def cursor(make, hx, hy, fallback):
    one, two = uri(make(24)), uri(make(48))
    return (
        f"cursor: {one} {hx} {hy}, {fallback};\n"
        f"  cursor: -webkit-image-set({one} 1x, {two} 2x) {hx} {hy}, {fallback};\n"
        f"  cursor: image-set({one} 1x, {two} 2x) {hx} {hy}, {fallback};"
    )


INK = "#1d1f2c"
VIOLET = "#5b54d6"

css = f"""/* The board's cursors — a cleaner take on Figma's: a crisp ink arrow with a
   white edge and a soft shadow, the same arrow in the board's violet over
   anything you can click, and a slim beam in text fields. Native CSS cursors
   (no JavaScript follower), so they never lag the pointer.

   Scoped to the v105 board and the surfaces it opens (stage, dialogs,
   popovers). Generated by cursor_gen.py — edit the drawing there, not here. */

html:has(.lgr-root[data-v="v105"]),
html:has(.lgr-root[data-v="v105"]) body {{
  {cursor(lambda s: arrow(INK, s), 5, 3, "default")}
}}

/* Anything clickable: the arrow turns violet. */
html:has(.lgr-root[data-v="v105"]) :is(
  a[href], button:not(:disabled), [role="button"]:not([aria-disabled="true"]), [role="tab"], [role="radio"],
  [role="menuitem"], [role="option"], [role="switch"], [role="checkbox"], select, summary, label[for],
  input[type="checkbox"], input[type="radio"], input[type="file"], .lgr-btn, .cm-pain, .cm-sh-th
),
html:has(.lgr-root[data-v="v105"]) :is(
  a[href], button:not(:disabled), [role="button"]:not([aria-disabled="true"]), [role="tab"], [role="radio"],
  [role="menuitem"], [role="option"], [role="switch"], [role="checkbox"], select, summary, label[for],
  .lgr-btn, .cm-pain, .cm-sh-th
) * {{
  {cursor(lambda s: arrow(VIOLET, s), 5, 3, "pointer")}
}}

/* Typing: the beam. */
html:has(.lgr-root[data-v="v105"]) :is(
  input:not([type="checkbox"]):not([type="radio"]):not([type="range"]):not([type="file"]):not([type="button"]):not([type="submit"]),
  textarea, [contenteditable="true"]
) {{
  {cursor(beam, 12, 12, "text")}
}}

/* Charts set their own cursor inline; let them inherit the board's. */
html:has(.lgr-root[data-v="v105"]) [_echarts_instance_],
html:has(.lgr-root[data-v="v105"]) [_echarts_instance_] * {{
  cursor: inherit !important;
}}

/* Disabled stays the system's — it has to read as "no". */
html:has(.lgr-root[data-v="v105"]) :is(button:disabled, [aria-disabled="true"]) {{
  cursor: not-allowed;
}}
"""
import sys
open(sys.argv[1], "w", encoding="utf-8", newline="\n").write(css)
print("ok", len(css))
